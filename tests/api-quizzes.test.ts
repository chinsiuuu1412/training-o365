test('Test manual submit rejects 59999 ms and permits exactly 60000 ms for a 90-second duration', async () => {
    const { fixture, quizzes, runner } = await setup('test');
    const revision = await quizzes.saveAnswers(1, runner.attempt, answers(runner));
    const saved = { ...runner.attempt, draft_revision: revision };
    fixture.setTime(baseTime + 59999);
    assert.equal(canSubmitManually(runner, fixture.now()), false);
    await assert.rejects(() => quizzes.submit(1, saved, crypto.randomUUID()), errorCode('early_submission'));
    fixture.setTime(baseTime + 60000);
    assert.equal(canSubmitManually(runner, fixture.now()), true);
    const result = await quizzes.submit(1, saved, crypto.randomUUID());
    assert.equal(result.attempt.score_percent, 100);
    assert.equal(result.attempt.submitted_at, new Date(baseTime + 60000).toISOString());
    assert.equal('questions' in result, false);
    assert.equal(result.review, null);
});
